import { Badge } from "@/components/ui/badge";
import {
  Card,
  CardContent,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { ToolLogo } from "@/components/ui/tool-logo";
import {
  getConfidenceLabel,
  getMigrationRiskLabel,
  TYPE_DISPLAY,
} from "@/lib/audit-recommendation-meta";
import { TOOL_NAMES } from "@/lib/pricing";
import { cn } from "@/lib/utils";
import type {
  AITool,
  SummarySource,
  ToolEntry,
  ToolRecommendation,
} from "@/types";

const SUMMARY_BADGE: Record<SummarySource, string> = {
  ai: "Generated by OpenAI",
  template: "Rule-based summary",
};

function SectionLabel({
  number,
  title,
  description,
}: {
  number: string;
  title: string;
  description?: string;
}) {
  return (
    <div className="mb-6 space-y-1">
      <p className="font-mono text-[10px] uppercase tracking-[0.2em] text-muted-foreground">
        {number}
      </p>
      <h2 className="font-display text-xl font-bold tracking-tight sm:text-2xl">
        {title}
      </h2>
      {description && (
        <p className="max-w-2xl text-sm leading-relaxed text-muted-foreground">
          {description}
        </p>
      )}
    </div>
  );
}

function SpendBreakdownBar({ tools }: { tools: ToolEntry[] }) {
  const total = tools.reduce((s, t) => s + t.monthlySpend, 0);
  if (total <= 0) return null;

  return (
    <div className="mb-8 space-y-2">
      <p className="font-mono text-[10px] uppercase tracking-wide text-muted-foreground">
        Spend mix by tool
      </p>
      <div className="flex h-3 overflow-hidden rounded-full border border-border bg-muted/30">
        {tools.map((entry) => {
          const pct = (entry.monthlySpend / total) * 100;
          if (pct < 0.5) return null;
          return (
            <div
              key={`${entry.tool}-${entry.plan}`}
              className="h-full bg-accent/70 first:rounded-l-full last:rounded-r-full"
              style={{ width: `${pct}%` }}
              title={`${TOOL_NAMES[entry.tool]}: $${entry.monthlySpend}/mo`}
            />
          );
        })}
      </div>
      <div className="flex flex-wrap gap-x-4 gap-y-1 text-[10px] text-muted-foreground">
        {tools.map((entry) => (
          <span key={`legend-${entry.tool}-${entry.plan}`}>
            {TOOL_NAMES[entry.tool]} ${entry.monthlySpend}/mo
          </span>
        ))}
      </div>
    </div>
  );
}

interface AuditSummaryProps {
  aiSummary: string;
  summarySource: SummarySource;
}

export function AuditSummary({ aiSummary, summarySource }: AuditSummaryProps) {
  const isAi = summarySource === "ai";

  return (
    <section aria-labelledby="audit-summary-heading">
      <SectionLabel
        number="01"
        title="Executive summary"
        description="AI consultant interpretation of your stack — team size, use case, and spending patterns."
      />
      <Card
        id="audit-summary-heading"
        className={cn(
          "rounded-xl bg-card shadow-sm",
          isAi ? "border border-accent/35" : "border border-border"
        )}
      >
        <CardHeader className="space-y-3 pb-4">
          <Badge
            variant="outline"
            className={cn(
              "w-fit font-mono text-[10px] uppercase tracking-wider",
              isAi && "border-accent/40 text-foreground"
            )}
          >
            {SUMMARY_BADGE[summarySource]}
          </Badge>
        </CardHeader>
        <CardContent className="pt-0">
          <p className="text-base leading-[1.75] text-foreground/90 sm:text-lg">
            {aiSummary}
          </p>
        </CardContent>
      </Card>
    </section>
  );
}

function buildSeatsMap(tools: ToolEntry[]): Map<string, number> {
  const map = new Map<string, number>();
  for (const t of tools) {
    map.set(`${t.tool}:${t.plan}`, t.seats);
  }
  return map;
}

interface AuditRecommendationsProps {
  recommendations: ToolRecommendation[];
  tools: ToolEntry[];
}

export function AuditRecommendations({
  recommendations,
  tools,
}: AuditRecommendationsProps) {
  const sorted = [...recommendations].sort((a, b) => b.savings - a.savings);
  const seatsMap = buildSeatsMap(tools);

  return (
    <section aria-labelledby="audit-recommendations-heading">
      <SectionLabel
        number="02"
        title="Per-tool audit"
        description="Each line item: current state, recommendation, savings, and financially defensible reasoning."
      />
      <SpendBreakdownBar tools={tools} />
      <div
        id="audit-recommendations-heading"
        className="space-y-6"
      >
        {sorted.map((rec, index) => {
          const hasSavings = rec.savings > 0;
          const seats =
            seatsMap.get(`${rec.tool}:${rec.currentPlan}`) ??
            tools.find((t) => t.tool === rec.tool)?.seats ??
            1;
          const typeMeta = TYPE_DISPLAY[rec.recommendationType];

          return (
            <Card
              key={`${rec.tool}-${rec.currentPlan}`}
              className={cn(
                "rounded-xl border bg-card shadow-sm",
                hasSavings
                  ? "border-l-[3px] border-l-accent border-border"
                  : "border-border"
              )}
            >
              <CardHeader className="flex flex-col gap-4 border-b border-border/60 pb-4 sm:flex-row sm:items-start sm:justify-between">
                <div className="flex min-w-0 items-start gap-3 sm:gap-4">
                  <span className="font-mono text-xs text-muted-foreground">
                    {String(index + 1).padStart(2, "0")}
                  </span>
                  <ToolLogo tool={rec.tool} className="h-10 w-10 shrink-0" />
                  <div className="min-w-0">
                    <CardTitle className="text-base font-semibold sm:text-lg">
                      {rec.toolName}
                    </CardTitle>
                    <p className="mt-1 font-mono text-[10px] uppercase tracking-wide text-muted-foreground">
                      {typeMeta.label}
                    </p>
                  </div>
                </div>
                <div className="flex flex-wrap items-center gap-1.5 sm:flex-col sm:items-end">
                  <Badge variant="outline" className="font-mono text-[10px]">
                    {getConfidenceLabel(rec.recommendationType)}
                  </Badge>
                  <Badge variant="secondary" className="font-mono text-[10px]">
                    {getMigrationRiskLabel(rec.recommendationType)}
                  </Badge>
                </div>
              </CardHeader>

              <CardContent className="grid gap-5 pt-5 sm:grid-cols-2">
                <div className="space-y-2 rounded-lg border border-border bg-muted/25 p-4">
                  <p className="font-mono text-[10px] uppercase tracking-wider text-muted-foreground">
                    Current state
                  </p>
                  <p className="font-medium capitalize text-foreground">
                    {rec.currentPlan}
                  </p>
                  <p className="font-mono text-sm text-muted-foreground">
                    {seats} seat{seats === 1 ? "" : "s"} · $
                    {rec.currentSpend}/month
                  </p>
                </div>

                <div className="space-y-2 rounded-lg border border-border bg-muted/15 p-4">
                  <p className="font-mono text-[10px] uppercase tracking-wider text-muted-foreground">
                    Recommended
                  </p>
                  <p className="font-medium text-foreground">
                    {rec.recommendedAction}
                  </p>
                  {rec.alternativeTool && (
                    <p className="text-xs text-muted-foreground">
                      Alternative:{" "}
                      {TOOL_NAMES[rec.alternativeTool as AITool] ??
                        rec.alternativeTool}
                    </p>
                  )}
                </div>

                {hasSavings && (
                  <div className="space-y-1 sm:col-span-2">
                    <p className="font-mono text-[10px] uppercase tracking-wider text-muted-foreground">
                      Savings
                    </p>
                    <p className="font-mono text-xl font-semibold tabular-nums text-savings">
                      Save ${rec.savings}/month · ${rec.annualSavings}/year
                    </p>
                  </div>
                )}

                <div
                  className={cn(
                    "space-y-2 border-l-2 border-accent/50 pl-4 sm:col-span-2",
                    !hasSavings && "border-muted-foreground/30"
                  )}
                >
                  <p className="font-mono text-[10px] uppercase tracking-wider text-muted-foreground">
                    Reasoning
                  </p>
                  <p className="text-sm leading-relaxed text-foreground/90 sm:text-base">
                    {rec.reason}
                  </p>
                </div>
              </CardContent>
            </Card>
          );
        })}
      </div>
    </section>
  );
}

interface AuditResultsProps {
  recommendations: ToolRecommendation[];
  tools: ToolEntry[];
  aiSummary: string;
  summarySource: SummarySource;
}

export default function AuditResults({
  recommendations,
  tools,
  aiSummary,
  summarySource,
}: AuditResultsProps) {
  return (
    <div className="space-y-14 sm:space-y-16">
      <AuditSummary aiSummary={aiSummary} summarySource={summarySource} />
      <AuditRecommendations recommendations={recommendations} tools={tools} />
    </div>
  );
}
